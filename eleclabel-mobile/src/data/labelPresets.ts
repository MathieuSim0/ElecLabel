// Filtrage par recherche texte (label + sublabel + category)
export function filterPresets(query: string): LabelPreset[] {
  const q = query.trim().toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "");
  if (!q) return LABEL_PRESETS;
  return LABEL_PRESETS.filter((p) => {
    const haystack = `${p.label} ${p.sublabel} ${p.category}`
      .toLowerCase()
      .normalize("NFD")
      .replace(/[̀-ͯ]/g, "");
    return haystack.includes(q);
  });
}
